// 如果馆（她 2026-08-31 提，形状她定的）
//
// 跟小剧场的分界要先说清楚，不然做出来就是第二个小剧场：
//   · 小剧场 = 【换掉两个人是谁】。身份、职业、世界全换，只留性格机制，张力现编。
//   · 如果馆 = 【两个人还是这两个人、这段关系还是这段关系】，只换掉【一个变量】。
// 她给的那几个例子（形态变了 / 换了时代 / 不记得了）全都落在后者上。
//
// ⚠️提示词里【不放她举的那几个例子】——放了模型就照着抄，每条线都长成同一个样子
//（见 .claude/rules/prompt-no-content-samples.md）。改成只写【判据】。
// ⚠️也【不给一张可动的东西清单】：清单是把例子往上抽一层，抄起来一样顺手，
// 再配上去重就成了排好班的轮转（见下面 OLD_DIM 那一段）。
(function (root) {
  "use strict";

  // 一拍里最多几个框。她要的是「一个气泡一个框、点一下出下一个」，
  // 所以一拍本来就该是好几框；但一口气二十框就成了念长文，点到手酸。
  const BOXES_MIN = 3, BOXES_MAX = 6;
  const BOX_CAP = 120;          // 单框字数：框是一口气读完的一屏，长了就不是框了
  const MY_BOXES_MAX = 8;       // 她一个回合能攒几条

  // ⚠️这里【不许再放一张「可动的东西」清单】。她 2026-08-31 点破：
  // 「这仨本质上还是给模型限制，用了去重的话那不就是每三轮轮一次一样的题材」。
  // 原来这儿列了四样（形态/时代/记忆/岔路口），去重块再叫它「从没动过的那几样里挑」——
  // 加起来就是一个四拍的轮盘：第五条必然转回第一条。**封闭清单 + 去重 ＝ 排好班的重复。**
  // 而且那四样本身就犯了 prompt-no-content-samples 那条：换个角色照样成立。
  // 现在改成：可动的东西【没有清单】，它得从 about（这条探的关系点）自己长出来。
  //
  // 存量翻译：v59.09 之前存下来的线，dim 存的是 form/era/memory/fork 这几个 key，
  // 界面上那一行「动的是：」要照样显示得出来。新的线 dim 直接就是一句中文。
  const OLD_DIM = { form: "他的形态", era: "他所处的时代", memory: "他还记不记得你", fork: "你俩那个岔路口" };
  const dimZh = function (v) { const k = String(v == null ? "" : v).trim(); return OLD_DIM[k] || k; };

  // 这条「如果」该有多大——她 2026-08-31 亲口划的那条线。
  // 只给【判据】：两头各挡一道，中间不给清单。给了清单它就在清单里转圈。
  //
  // ⚠️v59.11 撤掉的那句是「要让那一点现形，【最省事的一刀】砍在哪儿？就砍那儿」。
  // 她当天点破：「如果只留 about 关系的那不是完全没机会给那种离谱的出场机会了，
  // 比如如果你变成了小狗，如果你是外星人之类的」。对的，坏在「最省事」三个字上——
  // 它把选择压向最小最合理的那个介入，而「变成小狗」从来不是最省事的一刀。
  // 上一版的净效果是：关系点的花样多了，【壳的花样少了】。
  //
  // 病根是我把两根轴叠成了一根：写成「壳是手段、about 是目的」，筛壳的标准就变成
  // 「哪个壳最合理地服务于这个关系点」，答案永远是最温和的那个。四种组合里——
  // 离谱的壳＋真的关系点＝对；离谱的壳＋没 about＝猎奇；平淡的壳＋真的关系点＝八股。
  // 为了躲第二种，一路躲进了第三种。现在改成两轴各管各的，谁都不派生谁。
  const IF_SCALE = "【这条「如果」该有多大】\n"
    + "只动【一样】东西，动完之后其余一切照旧。\n"
    + "⚠️**没有一张「可以动什么」的清单，别去猜有哪几类。**\n"
    + "⚠️**壳离谱到什么程度都行。** 筛壳的判据不是「这个设定成不成立」、不是「这合不合理」，"
    + "只有一条——**动完之后他还是不是他**。过得了这一关，多离谱都不算过分；"
    + "过不了，多合理都不算数。\n"
    + "⚠️动完之后，【那个人的核心一个字都不许换】：脾气、说话的方式、在意什么、"
    + "对她的那点心思——这些换掉就不是「如果他怎样」，而是换了个人，那是小剧场的活。\n"
    + "⚠️也不许往小里写：只换一顿饭、一个地点、一次出门，那是今天的日程，不是如果。\n"
    + "⚠️**别往「稳妥」那头缩。** 这条线的前提说出口，如果不会让人愣一下，"
    + "那它多半太安全了，重想一个。\n"
    + "判据一句话：**换个角色照样成立的，就是想坏了。**";

  // 一拍怎么写。旁白和台词是【两种框】，界面上长得不一样，所以必须分开给。
  const IF_BEAT = "【怎么写这一拍】\n"
    + "把这一拍拆成 " + BOXES_MIN + "-" + BOXES_MAX + " 个【框】，一框一口气读完（" + BOX_CAP + "字以内）。\n"
    + "· who 留空＝旁白：写画面、动作、气味、光线，第三人称。\n"
    + "· who 填他的名字＝他说出口的话：只写话本身，别把动作塞进引号里。\n"
    + "两种框穿插着来，别整拍全是旁白、也别整拍全是对白。\n"
    + "⚠️绝不替她说话、绝不替她做决定——最后一框要落在一个她能接话的地方，"
    + "但不许写成一个问句清单逼她选。";

  function clip(s, n) {
    const v = String(s == null ? "" : s).replace(/\s+/g, " ").trim();
    return v.length > n ? v.slice(0, n) : v;
  }
  // 模型给的框收口成 [{who,text}]。who 只认【他的名字】或空——
  // 认别的名字等于让它替她说话，那是这一层最要紧的一条禁令。
  function normBoxes(raw, charName) {
    const arr = Array.isArray(raw) ? raw : (raw && Array.isArray(raw.boxes) ? raw.boxes : []);
    const out = [];
    arr.forEach(function (b) {
      if (!b) return;
      const text = clip(typeof b === "string" ? b : b.text, BOX_CAP);
      if (!text) return;
      const who = typeof b === "string" ? "" : clip(b.who, 24);
      const me = String(charName || "").trim();
      // ⚠️who 填了【别人】的名字（多半是她的）：整框丢掉，不要转成旁白留下来——
      // 转成旁白只是把名字摘了，那句话还是替她说的，而「绝不替她说话」是这一层
      // 最要紧的一条。宁可少一框。
      if (who && who !== me) return;
      out.push({ who: who ? me : "", text: text });
    });
    return out.slice(0, BOXES_MAX);
  }
  // 已经想过的那几条：原样发回去，让它自己岔开。
  // ⚠️只发【题目、前提、探的关系点、动掉的那一样】，不发正文——那是别的线的内容，
  // 混进来只会让它串味。
  // ⚠️这里【不许再算「还剩哪几样没动」】。她 2026-08-31：「用了去重的话那不就是每三轮
  // 轮一次一样的题材」——从一张有限的清单里挑没用过的，本来就是在排班，第 N+1 条必然
  // 转回第一条。去重只说【这些不许再来】，不说【那你去用剩下的那几个】。
  function avoidBlock(prior) {
    const list = (Array.isArray(prior) ? prior : []).slice(0, 8);
    const rows = list
      .map(function (x) {
        if (!x || !x.title) return "";
        // about 也要发回去：换个壳、探的还是同一个关系点，那也是重复——
        // 而且是更难发现的那一种（题目看着不一样，读起来一模一样）。
        return "· 「" + x.title + "」：" + String(x.premise || "").slice(0, 40)
          + (x.about ? "｜探的是：" + String(x.about).slice(0, 30) : "")
          + (x.dim ? "｜动的是：" + dimZh(x.dim).slice(0, 20) : "");
      })
      .filter(Boolean);
    if (!rows.length) return "";
    return "\n\n【已经想过这几条，一条都不许再想】\n" + rows.join("\n")
      + "\n⚠️不是换个说法就算新的，有两种都算重复：\n"
      + "① **同一样东西变了、只是换个词说**——上面写着「动的是」的那几样，一样都不许再动；\n"
      + "② **换了个壳、探的还是同一个关系点**——上面写着「探的是」的那几样，一个都不许再探。\n"
      + "⚠️**别顺着上面那几条往同一类里再找一个。** 上面这几条不是一张分类表、"
      + "不是「还剩几格没填」——它们只是几个已经用掉的答案。这一条要从 about 重新起头："
      + "先想一个上面没探过的关系点，再倒推该动哪一样，而不是先在上面那几样旁边挑个近亲。";
  }
  // ⚠️她 2026-08-31 点破的那个：人设里最显眼的一块（多半是职业/研究领域）会把模型
  // 整个吸过去，于是每条线都在那一块里打转，压根想不到关系。小剧场早就栽过同一个坑、
  // 也留了同一句话（「原本搞研究就总派研究员，这是偷懒」）。
  //
  // 两道一起下：① 明令不许拿职业当题目；② 逼它【先写这条线探的是你俩之间的哪一点】，
  // 再去想壳——顺序本身就是结构，先写关系就没法再从职业出发。
  const IF_ABOUT = "【这条线得有分量】\n"
    + "这条线要探的是【你们两个人之间的一样东西】——不是他一个人的处境，更不是他的行当。\n"
    + "把它写进 about：你俩之间哪一点，是把它拿掉、或者反过来，才看得出它一直在那儿的？"
    + "（谁一直在等谁、谁先开口、哪句话始终没说、你俩之间靠什么维系着、"
    + "有一样东西是不是一直被当成理所当然的……方向是这一类，不是让你照着填。）\n"
    + "⚠️**绝不许拿他的职业、研究领域、专业身份当这条线的题目。** 那是他人设里最显眼的一块，"
    + "抓它最省力，也最没意思——一连几条都长在同一个行当上，就是这么来的。"
    + "换个职业照样成立的关系难题才是对的，反过来【换个职业就不成立】的题目一律推翻重想。\n"
    + "**about 和壳是两件事，两件都要有，谁也不是谁的仆人**："
    + "about 管这条线【有没有分量】，壳管这条线【有没有意思】。\n"
    + "所以两个方向都行：想到一个关系点，再去找哪个壳最能把它逼出来；"
    + "或者先想到一个离谱的壳，再问它到底逼出了你俩之间的哪一点。\n"
    + "⚠️**只有一种不行：有壳、没 about。** 那就只是个猎奇设定，写不动第二拍。";
  function openPrompt(charName, uName, hint, prior) {
    const h = clip(hint, 200);
    return "你要为「" + charName + "」和「" + uName + "」想一条【如果线】，然后把它的开场写出来。\n"
      + "这不是换一个世界换一批人：**他俩还是他俩，这段关系还是这段关系**，只是当初有一样东西不一样了。\n\n"
      + IF_SCALE + "\n\n"
      + (h ? "【她给的方向】" + h + "\n这就是这条线要走的方向，按它来，别另起炉灶。\n\n"
           : "【她没给方向】那就自己想一条：从你俩之间的哪一点起头，或者从一个离谱的壳起头，都行——"
             + "但交上来的时候两样都得有。\n"
             + "别挑那个最顺手的——换个角色照样成立的，就是想坏了。\n\n")
      + IF_ABOUT + "\n\n"
      + IF_BEAT + avoidBlock(prior) + "\n\n"
      + "按这个顺序给（顺序只是写下来的顺序，不规定你先想哪个；但 about 空着一律作废）："
      + "about＝这条线探的是你俩之间的哪一点；"
      + "title＝这条线叫什么（八个字以内，别剧透结局）；"
      + "premise＝一句话说清哪一样不一样了；"
      + "dim＝这条到底动掉了哪一样东西（十个字以内的一句中文，照实写，不要往哪一类上靠）；"
      + "bg＝这条线的背景画面提示词（一句英文，只写地方和光线氛围，不要写人）。";
  }
  function beatPrompt(charName, uName) {
    return "接着往下演这一拍。\n" + IF_BEAT + "\n\n"
      + "⚠️别急着收尾，也别开新线头往外岔——顺着刚才那一下往前走一步就好。\n"
      + "「" + uName + "」刚才那几句就在上面，接住她真正说的那句，别当没看见。";
  }
  const OPEN_SHAPE = "{\"about\":\"这条线探的是你俩之间的哪一点\",\"title\":\"这条线叫什么\",\"premise\":\"哪一样不一样了，一句话\",\"dim\":\"这条动掉的那一样东西，十字以内\",\"bg\":\"背景画面提示词，一句英文\",\"boxes\":[{\"who\":\"留空＝旁白，填名字＝他说的话\",\"text\":\"这一框的内容\"}]}";
  const BEAT_SHAPE = "{\"boxes\":[{\"who\":\"留空＝旁白，填名字＝他说的话\",\"text\":\"这一框的内容\"}]}";

  const api = {
    BOXES_MIN: BOXES_MIN, BOXES_MAX: BOXES_MAX, BOX_CAP: BOX_CAP, MY_BOXES_MAX: MY_BOXES_MAX,
    IF_SCALE: IF_SCALE, IF_BEAT: IF_BEAT, IF_ABOUT: IF_ABOUT, dimZh: dimZh, avoidBlock: avoidBlock,
    normBoxes: normBoxes, openPrompt: openPrompt, beatPrompt: beatPrompt,
    OPEN_SHAPE: OPEN_SHAPE, BEAT_SHAPE: BEAT_SHAPE
  };
  if (typeof module !== "undefined" && module.exports) module.exports = api;
  // ⚠️叫 IfKit 不叫 IfRoom：screens.js 里那个页面组件就叫 IfRoom，两个都是全局，
  // 后加载的这一个会把组件函数原样盖成一个对象，React 当场报 #130（元素类型不是
  // 函数是对象）——而 node --check 和整套测试一个字都不会说。跟房里 GachaKit /
  // HeartKit / TrpgMap 一个叫法。
  if (root) root.IfKit = api;
})(typeof window !== "undefined" ? window : globalThis);
