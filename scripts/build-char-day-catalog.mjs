// Generate the schedule adapter from the real scene/position owners, never from a second list.
import {writeFileSync} from 'node:fs';
import {registerHooks} from 'node:module';
export async function buildDayCatalog(){
 const hook=registerHooks({resolve(specifier,context,next){return specifier==='three'?{url:new URL('../apps/fairy-garden/vendor/three.module.js',import.meta.url).href,shortCircuit:true}:next(specifier,context);}});
 try{
  const {DAY_PLACES}=await import('../apps/fairy-garden/day/places/index.mjs');
  const {CORE_SPACES}=await import('../apps/fairy-garden/day/spaces.mjs');
  const catalog=Object.entries({...CORE_SPACES,...DAY_PLACES}).map(([id,m])=>({id,label:m.label,spots:m.spots.map(({id,label,action,gesture})=>({id,label,action,gesture}))}));
  const src='// Generated by scripts/build-char-day-catalog.mjs from the actual scene maps.\n'+
   '(function(root){root.CharDayCatalog='+JSON.stringify(catalog,null,2)+';})(globalThis);\n';
  writeFileSync(new URL('../apps/fairy-garden/day/catalog.js',import.meta.url),src);
  return catalog;
 }finally{hook.deregister();}
}
if(process.argv[1]&&new URL('file://'+process.argv[1]).href===import.meta.url)await buildDayCatalog();
