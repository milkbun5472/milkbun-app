const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const app = fs.readFileSync(path.join(__dirname, "..", "js", "app.js"), "utf8");
// ⚠️锚在「const gapHint」这个名字上，别锚在它当时的整行条件上——
//   v60.15 给它加了个 !sideRoom 前缀，indexOf 就成了 -1，切片变成空串，
//   下面四条断言当场全红，看着像提示词被删了，其实一个字没动。
const _gi = app.indexOf("const gapHint");
const gap = app.slice(_gi, app.indexOf("let lastPrivateUserTs = 0;", _gi));

// 她 2026-08-31：「我记得整体提示词里我们塞了一个如果不回是在忙不要生气质问，
// 所以其实他们也没办法 mood 减下来，要不把那块提示词删了吧」。
//
// 她说得对：那句话是【情绪禁令】——不许因为久没回而不高兴。代价是心情永远降不下来，
// 于是「和好间」这类靠情绪信号触发的东西根本察觉不到，App 里也就没有真正的别扭。
test("久没回之后，情绪不再被禁掉", () => {
  ["别质问『怎么才回我』", "愧疚绑架", "甩脸子摆委屈闹脾气",
   "Ta 同时要顾着生活和别的人、不是随时都能回你，这很正常"]
    .forEach(k => assert.ok(app.indexOf(k) < 0, "那句情绪禁令还在：" + k));
  assert.match(gap, /你心里是什么感觉就按你这个人真实的感觉来/, "删了却没说清该按什么来");
});

// ⚠️换成「该生气就生气」只是把一个偏置换成另一个偏置。要的是【允许整个谱】、不指方向。
test("解禁不等于改成催他生气", () => {
  assert.match(gap, /高兴、想她、无所谓、有点闷、甚至有点不痛快，都可以/, "没把整个谱都放开");
  assert.ok(!/该生气就生气|应该不高兴|要表现出委屈/.test(gap), "从一个偏置换成了另一个偏置");
  // 解禁的是【情绪】，不是【腔调】：网文那套摆委屈桥段仍然不要
  assert.match(gap, /不是网文里那套摆委屈闹脾气的通用桥段/, "连腔调那道防线也一起拆了");
});

// 爽约那一段是她 2026-07-18 自己点名要的，管的是【别把没发生的软性约定说成她爽约】
// ——那是编事实，不是情绪，所以留着；但边界要写死，别被泛化成通用情绪禁令。
test("「别把没发生的约说成爽约」留着，而且不许外溢", () => {
  assert.match(gap, /【绝不许】默认她爽约、放你鸽子/, "把编事实那道防线也一起删了");
  assert.match(gap, /软性的『我来找你』本就不是签了字的约会/, "理由没了");
  assert.match(gap, /这一条只管【这件没发生的约】，不外溢/, "没把边界写死，会被泛化回通用情绪禁令");
  assert.match(gap, /你对「她这段时间没回你」本身是什么感觉，照上面那句/, "没指回上面那条");
});

// 时间流逝那一半跟情绪无关，别一起删掉
test("时间流逝要体现出来这一半没被误伤", () => {
  assert.match(gap, /别当作刚刚才聊过/);
  assert.match(gap, /接上之前没做完\/说要去做的事/);
  assert.match(gap, /贴合此刻时间点/);
});

// 另一处「不质问为什么没回」在【他主动开口】那一支上：那一支的意思是「重新来敲门、
// 别拿上一轮的情绪开场」，管的是【开场方式】不是【能不能有情绪】，所以留着。
test("他主动开口那一支是另一件事，留着", () => {
  assert.match(app, /像真人隔一阵重新来敲门，不复述旧话、不质问为什么没回/, "把主动开口那一支也一起删了");
  assert.match(app, /不要延续上一轮的委屈、焦虑、兴奋或争执情绪/, "那一支的本意（别拿旧情绪开场）没了");
});
